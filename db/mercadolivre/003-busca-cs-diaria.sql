CREATE TABLE IF NOT EXISTS busca_cs_diaria (
  contas CHAR(64) NOT NULL,
  dia CHAR(8) NOT NULL,
  total_notas BIGINT UNSIGNED NOT NULL,
  valor_bruto DECIMAL(18,2) NOT NULL,
  atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (contas, dia)
) ENGINE=InnoDB;
